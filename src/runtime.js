import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { TOOL_VERSION } from './version.js';

const SRC_DIR = path.dirname(fileURLToPath(import.meta.url));

export function stripModuleSyntax(source) {
  return source
    .replace(/^\s*import\s.+;?\s*$/gm, '')
    .replace(/^export\s+function\s+/gm, 'function ')
    .replace(/^export\s+const\s+/gm, 'const ')
    .replace(/^export\s+\{[^}]*\};?\s*$/gm, '');
}

export function loadInlinedSources() {
  const engine = stripModuleSyntax(fs.readFileSync(path.join(SRC_DIR, 'engine.js'), 'utf8'));
  const dom = stripModuleSyntax(fs.readFileSync(path.join(SRC_DIR, 'dom.js'), 'utf8'));
  if (/\bexport\s/.test(engine) || /\bexport\s/.test(dom)) {
    throw new Error('内联运行时仍含有 export，无法注入页面');
  }
  return { engine, dom };
}

export function dictionaryPayload(raw) {
  return {
    exact: raw.exact || {},
    fragments: raw.fragments || [],
    regex: (raw.regex || []).map((item) => ({
      id: item.id,
      pattern: item.pattern,
      flags: item.flags || '',
      replacement: item.replacement,
    })),
    placeholders: raw.placeholders || [],
  };
}

export function buildRuntimeScript(rawDictionary, version = TOOL_VERSION) {
  const { engine, dom } = loadInlinedSources();
  const payload = JSON.stringify(dictionaryPayload(rawDictionary));
  return `/* cursor-zh-hans ${version}
 * Unofficial Agents Window translation. Skips editor, terminal, diff, chat, and inputs.
 * This file is generated by the patcher. Do not edit inside the Cursor install.
 */
${engine}
${dom}
startDomTranslator({
  translateText: translateText,
  shouldSkipElement: shouldSkipElement,
  shouldSkipAttributeTarget: shouldSkipAttributeTarget,
  skipReason: skipReason,
  dictionary: compileDictionary(${payload}),
  version: ${JSON.stringify(version)}
}, {
  document: document,
  MutationObserver: MutationObserver,
  Element: Element,
  window: window,
  now: function () { return Date.now(); },
  budgetMs: 2000,
  scheduleSoon: function (fn) { setTimeout(fn, 0); },
  scheduleIdle: function (fn) {
    if (typeof requestIdleCallback === 'function') return requestIdleCallback(fn, { timeout: 50 });
    return setTimeout(fn, 1);
  },
  cancelIdle: function (id) {
    if (typeof cancelIdleCallback === 'function') cancelIdleCallback(id);
    else clearTimeout(id);
  }
});
`;
}
